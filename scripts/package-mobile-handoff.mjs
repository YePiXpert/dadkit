import {
  copyFileSync,
  existsSync,
  mkdirSync,
  readFileSync,
  rmSync,
  statSync,
  writeFileSync,
} from "node:fs";
import { createHash } from "node:crypto";
import { basename, join } from "node:path";

import {
  ANDROID_DEBUG_APK,
  ANDROID_PACKAGE_ID,
  APP_NAME,
  APP_VERSION,
} from "./mobile-env.mjs";
import {
  createMobileHandoffArchive,
  handoffArchiveName,
} from "./create-mobile-handoff-archive.mjs";

const outDir = join(process.cwd(), "dist", "mobile-handoff");
const apkName = `dadkit-${APP_VERSION}-debug.apk`;
const apkOut = join(outDir, apkName);
const checksumOut = join(outDir, `${apkName}.sha256`);
const metadataOut = join(outDir, "metadata.json");
const readmeOut = join(outDir, "README.md");
const indexOut = join(outDir, "index.html");
const readinessReportOut = join(outDir, "readiness-report.md");
const readinessReportJsonOut = join(outDir, "readiness-report.json");
const testerGuideSource = join(process.cwd(), "docs", "mobile-tester-guide.md");
const testerGuideOut = join(outDir, "tester-guide.md");
const coverSource = join(process.cwd(), "resources", "store", "dadkit-handoff-cover.png");
const coverOut = join(outDir, "cover.png");
const playFeatureSource = join(
  process.cwd(),
  "resources",
  "store",
  "dadkit-google-play-feature.png",
);
const playFeatureOut = join(outDir, "google-play-feature.png");
const screenshotsDir = join(outDir, "screenshots");
const screenshotsManifest = join(screenshotsDir, "manifest.json");
const storeScreenshotsDir = join(outDir, "store-screenshots", "app-store-6-9");
const storeScreenshotsManifest = join(storeScreenshotsDir, "manifest.json");

if (!existsSync(ANDROID_DEBUG_APK)) {
  console.error(`Android debug APK not found: ${ANDROID_DEBUG_APK}`);
  console.error("Run `npm run mobile:android:debug` first.");
  process.exit(1);
}

const apkStats = statSync(ANDROID_DEBUG_APK);

if (apkStats.size <= 0) {
  console.error(`Android debug APK is empty: ${ANDROID_DEBUG_APK}`);
  process.exit(1);
}

mkdirSync(outDir, { recursive: true });
for (const file of [
  apkOut,
  checksumOut,
  metadataOut,
  readmeOut,
  indexOut,
  readinessReportOut,
  readinessReportJsonOut,
  testerGuideOut,
  coverOut,
  playFeatureOut,
  join(outDir, handoffArchiveName),
]) {
  rmSync(file, { force: true });
}
copyFileSync(ANDROID_DEBUG_APK, apkOut);

if (existsSync(testerGuideSource)) {
  copyFileSync(testerGuideSource, testerGuideOut);
}

if (existsSync(coverSource)) {
  copyFileSync(coverSource, coverOut);
}

if (existsSync(playFeatureSource)) {
  copyFileSync(playFeatureSource, playFeatureOut);
}

const apkBuffer = readFileSync(apkOut);
const sha256 = createHash("sha256").update(apkBuffer).digest("hex");
const createdAt = new Date().toISOString();

writeFileSync(checksumOut, `${sha256}  ${apkName}\n`, "utf8");
const screenshots = readScreenshots();
const storeScreenshots = readStoreScreenshots();
writeFileSync(
  metadataOut,
  `${JSON.stringify(
    {
      appName: APP_NAME,
      version: APP_VERSION,
      packageId: ANDROID_PACKAGE_ID,
      buildType: "debug",
      apk: basename(apkOut),
      bytes: apkStats.size,
      sha256,
      createdAt,
      installCommand: "npm run mobile:android:install",
      webdavAcceptanceCommand: "npm run mobile:android:webdav:verify:prompt",
      cover: existsSync(coverOut) ? "cover.png" : undefined,
      googlePlayFeatureGraphic: existsSync(playFeatureOut)
        ? "google-play-feature.png"
        : undefined,
      screenshots: screenshots.map((item) => item.file),
      appStoreScreenshots: storeScreenshots.map((item) => item.file),
      handoffIndex: "index.html",
      handoffArchive: handoffArchiveName,
      testerGuide: existsSync(testerGuideOut) ? "tester-guide.md" : undefined,
      readinessReport: "readiness-report.md",
      readinessReportJson: "readiness-report.json",
    },
    null,
    2,
  )}\n`,
  "utf8",
);
writeFileSync(
  readmeOut,
  `# ${APP_NAME} Android test handoff

Generated: ${createdAt}

## Files

- \`${apkName}\` - debug APK for local testing.
- \`${apkName}.sha256\` - SHA-256 checksum.
- \`metadata.json\` - package id, version, size, and verification commands.
- \`index.html\` - tester-friendly overview with install notes and screenshots.
- \`${handoffArchiveName}\` - shareable ZIP for sending the APK, guide, screenshots, and reports together.
- \`tester-guide.md\` - tester checklist and feedback template.
- \`cover.png\` - image2-generated visual cover for the tester overview.
- \`google-play-feature.png\` - image2-generated 1024x500 Google Play feature graphic draft.
- \`readiness-report.md\` - generated by \`npm run mobile:handoff:verify\`.
- \`screenshots/\` - optional mobile screenshots generated by
  \`npm run mobile:handoff:screenshots\`.
- \`store-screenshots/app-store-6-9/\` - optional 1290x2796 App Store
  screenshot drafts generated by \`npm run mobile:handoff:store-screenshots\`.

## Install

Send \`${apkName}\` to the tester and install it on Android. This is a debug
build for direct testing, not a store-ready release.

For a USB-connected device from this repo:

\`\`\`powershell
npm run mobile:android:install
\`\`\`

## Verify WebDAV

Use the prompt command so credentials stay out of shell history, docs, and logs:

\`\`\`powershell
npm run mobile:android:webdav:verify:prompt
\`\`\`

Expected remote backup path:

\`\`\`
https://webdav.123pan.cn/webdav/DadKit/dadkit-backup.json
\`\`\`

## Release note

A production Android release still needs a private release keystore and
\`npm run mobile:android:release\` or \`npm run mobile:android:release:aab\`.
Do not distribute keystore files or passwords with this test handoff.
`,
  "utf8",
);
writeFileSync(
  indexOut,
  renderIndex({ apkName, sha256, createdAt, screenshots, storeScreenshots }),
  "utf8",
);

const archive = createMobileHandoffArchive();

console.log(`Created Android handoff package: ${outDir}`);
console.log(`Archive: ${archive.path}`);
console.log(`APK: ${apkOut}`);
console.log(`Index: ${indexOut}`);
console.log(`SHA-256: ${sha256}`);

function readScreenshots() {
  if (!existsSync(screenshotsManifest)) {
    return [];
  }

  const manifest = JSON.parse(readFileSync(screenshotsManifest, "utf8"));

  return (manifest.manifest ?? [])
    .filter((entry) => entry.file && existsSync(entry.file))
    .map((entry) => ({
      name: entry.name,
      route: entry.route,
      file: `screenshots/${basename(entry.file)}`,
      width: entry.state?.width,
      scrollWidth: entry.state?.scrollWidth,
      bodyScrollWidth: entry.state?.bodyScrollWidth,
    }));
}

function readStoreScreenshots() {
  if (!existsSync(storeScreenshotsManifest)) {
    return [];
  }

  const manifest = JSON.parse(readFileSync(storeScreenshotsManifest, "utf8"));

  return (manifest.manifest ?? [])
    .filter((entry) => {
      if (!entry.file) {
        return false;
      }

      return existsSync(join(outDir, entry.file));
    })
    .map((entry) => ({
      name: entry.name,
      route: entry.route,
      file: entry.file,
      width: entry.state?.width,
      scrollWidth: entry.state?.scrollWidth,
      bodyScrollWidth: entry.state?.bodyScrollWidth,
    }));
}

